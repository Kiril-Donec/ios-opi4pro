/*
 * Host test for the pure part of bsd/dev/a733_usbtouch.c
 * (a733/xnu-a733-usbtouch.patch): HID report descriptor parsing, report
 * decoding and the touch -> SweetHIDTouch panel mapping.
 * test_usbtouch_patch.py cuts the driver out of the patch and builds it
 * with -include and -DA733_USBTOUCH_HOST_TEST.
 *
 * The descriptor and reports are the display's own touch controller
 * (wch.cn USB2IIC_CTP_CONTROL 1a86:e5e3), read from hidraw on a PC
 * (2026-10-22): 6 finger slots, X/Y 0..2048, report ID 1, 52 bytes.
 */
#include <stdio.h>
#include <stdlib.h>

static int failures;
#define CHECK(cond) do { \
	if (!(cond)) { \
		fprintf(stderr, "FAIL %s:%d: %s\n", __FILE__, __LINE__, #cond); \
		failures++; \
	} \
} while (0)

