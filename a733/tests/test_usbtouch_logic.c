static void
report(uint8_t *r, const uint8_t (*fingers)[4], unsigned n)
{
	memset(r, 0, 52);
	r[0] = 1;
	for (unsigned i = 0; i < n; i++) {
		uint8_t *f = r + 1 + 8 * i;
		uint16_t x = (uint16_t)(fingers[i][2] << 4), y = (uint16_t)(fingers[i][3] << 4);
		f[0] = fingers[i][0];
		f[1] = fingers[i][1];
		f[2] = (uint8_t)x;
		f[3] = (uint8_t)(x >> 8);
		f[4] = (uint8_t)y;
		f[5] = (uint8_t)(y >> 8);
		f[6] = 0x30;
	}
	r[49] = 1;
	r[50] = 1;
	r[51] = (uint8_t)n;
}

/* Inverse of the display path: the panel pixel shown at portrait (px, py). */
static void
portrait_to_panel(int px, int py, int *x, int *y)
{
	const int view_w = 473, left = 63;
	int vx = px - left;
	*x = (int)((int64_t)vx * 1125 / view_w) - 20;     /* a733_cpu_present: sx = vx * w / view_w */
	*y = (int)((int64_t)py * 2436 / 1024) - 18;
}

static void
test_descriptor(void)
{
	struct ut_layout l;
	CHECK(ut_parse_report_descriptor(ctp_descriptor, sizeof(ctp_descriptor), &l) == 0);
	CHECK(l.report_id == 1);
	CHECK(l.fingers == 6);
	CHECK(l.report_bits == 51 * 8);                 /* 6 x 8 bytes + scan time + count */
	for (unsigned f = 0; f < 6; f++) {
		CHECK(l.finger[f].tip.bit == 64 * f && l.finger[f].tip.size == 1);
		CHECK(l.finger[f].id.bit == 64 * f + 8 && l.finger[f].id.size == 8);
		CHECK(l.finger[f].x.bit == 64 * f + 16 && l.finger[f].x.size == 16 && l.finger[f].x.lmax == 2048);
		CHECK(l.finger[f].y.bit == 64 * f + 32 && l.finger[f].y.size == 16 && l.finger[f].y.lmax == 2048);
	}
	CHECK(l.count.bit == 400 && l.count.size == 8);
	/* Truncated or empty descriptors are refused, never read past the end. */
	for (unsigned n = 0; n < 40; n++) {
		CHECK(ut_parse_report_descriptor(ctp_descriptor, n, &l) != 0);
	}
	static const uint8_t mouse[] = {
		0x05, 0x01, 0x09, 0x02, 0xa1, 0x01, 0x09, 0x01, 0xa1, 0x00, 0x05, 0x09, 0x19, 0x01, 0x29, 0x03,
		0x15, 0x00, 0x25, 0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02, 0x95, 0x01, 0x75, 0x05, 0x81, 0x01,
		0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x15, 0x81, 0x25, 0x7f, 0x75, 0x08, 0x95, 0x02, 0x81, 0x06,
		0xc0, 0xc0,
	};
	CHECK(ut_parse_report_descriptor(mouse, sizeof(mouse), &l) == EINVAL);
}

static void
test_decode(void)
{
	struct ut_layout l;
	struct ut_contact c[UT_MAX_FINGERS];
	CHECK(ut_parse_report_descriptor(ctp_descriptor, sizeof(ctp_descriptor), &l) == 0);

	/* Recorded: one finger down at X 916, Y 1078. */
	static const uint8_t one[52] = {
		0x01, 0x01, 0x00, 0x94, 0x03, 0x36, 0x04, 0x30, [49] = 0x01, 0x01, 0x01,
	};
	CHECK(ut_decode(&l, one, sizeof(one), c) == 6);
	CHECK(c[0].down && c[0].id == 0 && c[0].x == 916 && c[0].y == 1078);
	for (unsigned f = 1; f < 6; f++) {
		CHECK(!c[f].down);
	}
	/* Recorded: four fingers, contact 2 lifting (tip 0) while 0, 1, 3 stay. */
	static const uint8_t four[52] = {
		0x01, 0x01, 0x00, 0x82, 0x04, 0x44, 0x04, 0x30, 0x00, 0x01, 0x01, 0x90, 0x05, 0x6d, 0x02, 0x30,
		0x00, 0x00, 0x02, 0x5a, 0x06, 0xa3, 0x02, 0x30, 0x00, 0x01, 0x03, 0xf6, 0x04, 0x28, 0x03, 0x30,
		[49] = 0x01, 0x01, 0x04,
	};
	CHECK(ut_decode(&l, four, sizeof(four), c) == 6);
	CHECK(c[0].down && c[0].x == 1154 && c[0].y == 1092);
	CHECK(c[1].down && c[1].id == 1 && c[1].x == 1424 && c[1].y == 621);
	CHECK(!c[2].down && c[2].id == 2);
	CHECK(c[3].down && c[3].id == 3 && c[3].x == 1270 && c[3].y == 808);
	/* Other report IDs and short packets are ignored. */
	uint8_t other[52];
	memcpy(other, one, sizeof(other));
	other[0] = 3;
	CHECK(ut_decode(&l, other, sizeof(other), c) == -1);
	CHECK(ut_decode(&l, one, 51, c) == -1);
	CHECK(ut_decode(&l, one, 0, c) == -1);
	uint8_t built[52];
	static const uint8_t two[2][4] = { { 1, 5, 64, 32 }, { 1, 9, 100, 120 } };
	report(built, two, 2);
	CHECK(ut_decode(&l, built, sizeof(built), c) == 6);
	CHECK(c[0].id == 5 && c[0].x == 1024 && c[0].y == 512 && c[1].id == 9 && c[1].x == 1600);
}

static void
test_orientation(void)
{
	const struct ut_orient o = { false, false, false };
	int x, y;

	/* Touch origin = landscape top-left = portrait top-right (Stage0 rotation). */
	ut_map(0, 0, 2048, 2048, o, &x, &y);
	CHECK(x > 1079 && y < 0);                       /* SweetHIDTouch clamps to 1079, 0 */
	/* Landscape bottom-right = portrait bottom-left. */
	ut_map(2048, 2048, 2048, 2048, o, &x, &y);
	CHECK(x < 0 && y > 2399);
	/* Landscape top-right (X max, Y 0) = portrait bottom-right. */
	ut_map(2048, 0, 2048, 2048, o, &x, &y);
	CHECK(x > 1079 && y > 2399);
	/* Centre of the glass = centre of the iPhone screen. */
	ut_map(1024, 1024, 2048, 2048, o, &x, &y);
	CHECK(abs(x - 540) <= 3 && abs(y - 1200) <= 3);
	/* Out-of-range raw values are clamped, not wrapped. */
	int x2, y2;
	ut_map(5000, 5000, 2048, 2048, o, &x2, &y2);
	ut_map(2048, 2048, 2048, 2048, o, &x, &y);
	CHECK(x == x2 && y == y2);

	/*
	 * Every displayed portrait pixel: a touch on it must land on the panel
	 * pixel that a733_cpu_present() draws there (within one source pixel;
	 * the 473-column view is scaled up ~2.4x).
	 */
	int worst = 0;
	for (int py = 0; py < 1024; py += 7) {
		for (int px = 63; px < 63 + 473; px += 5) {
			/* Portrait -> physical (row 599 - px, column py) -> raw touch. */
			uint32_t col = (uint32_t)py, row = (uint32_t)(599 - px);
			uint32_t rx = (col * 2048 + 511) / 1023, ry = (row * 2048 + 299) / 599;
			int ex, ey;
			ut_map(rx, ry, 2048, 2048, o, &x, &y);
			portrait_to_panel(px, py, &ex, &ey);
			int d = abs(x - ex) > abs(y - ey) ? abs(x - ex) : abs(y - ey);
			worst = d > worst ? d : worst;
		}
	}
	CHECK(worst <= 3);

	/* Moving the finger along the glass moves it the right way on the iPhone screen. */
	int ax, ay, bx, by;
	ut_map(1000, 1000, 2048, 2048, o, &ax, &ay);
	ut_map(1400, 1000, 2048, 2048, o, &bx, &by);    /* along X = along the long side */
	CHECK(by > ay + 400 && abs(bx - ax) <= 1);      /* portrait: downwards */
	ut_map(1000, 1400, 2048, 2048, o, &bx, &by);    /* along Y = short side, landscape down */
	CHECK(bx < ax - 250 && abs(by - ay) <= 1);      /* portrait: to the left */

	/* The boot-arg fixes act on the raw axes. */
	struct ut_orient s = { true, false, false }, fx = { false, true, false }, fy = { false, false, true };
	ut_map(2048, 0, 2048, 2048, s, &x, &y);
	ut_map(0, 2048, 2048, 2048, o, &x2, &y2);
	CHECK(x == x2 && y == y2);
	ut_map(0, 500, 2048, 2048, fx, &x, &y);
	ut_map(2048, 500, 2048, 2048, o, &x2, &y2);
	CHECK(x == x2 && y == y2);
	ut_map(500, 0, 2048, 2048, fy, &x, &y);
	ut_map(500, 2048, 2048, 2048, o, &x2, &y2);
	CHECK(x == x2 && y == y2);
	/* A degenerate logical maximum does not divide by zero. */
	ut_map(10, 10, 0, 0, o, &x, &y);
}

int
main(void)
{
	test_descriptor();
	test_decode();
	test_orientation();
	if (failures) {
		printf("FAIL (%d)\n", failures);
		return 1;
	}
	printf("A733 USB touch logic: PASS\n");
	return 0;
}
